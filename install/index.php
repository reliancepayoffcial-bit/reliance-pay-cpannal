    'mbstring' => extension_loaded('mbstring'),
    'ctype' => extension_loaded('ctype')
];
$phpVersionOk = version_compare(PHP_VERSION, '8.1.0', '>=');
$uploadDirWritable = is_writable(__DIR__ . '/../public/uploads') || @mkdir(__DIR__ . '/../public/uploads', 0755, true);
$configDirWritable = is_writable(__DIR__ . '/../config') || is_writable(__DIR__ . '/../config/database.php');

$allRequirementsMet = $phpVersionOk && !in_array(false, $extensions, true) && $uploadDirWritable && $configDirWritable;

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if ($step === 2) {
        $dbHost = trim($_POST['db_host'] ?? 'localhost');
        $dbPort = trim($_POST['db_port'] ?? '3306');
        $dbName = trim($_POST['db_name'] ?? '');
        $dbUser = trim($_POST['db_user'] ?? '');
        $dbPass = trim($_POST['db_pass'] ?? '');

        if (empty($dbName) || empty($dbUser)) {
            $error = 'Database Name and Database Username are required.';
        } else {
            try {
                $dsn = "mysql:host={$dbHost};port={$dbPort};charset=utf8mb4";
                $pdo = new PDO($dsn, $dbUser, $dbPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
                
                // Create database if not exists
                $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
                $pdo->exec("USE `{$dbName}`");

                $_SESSION['db_host'] = $dbHost;
                $_SESSION['db_port'] = $dbPort;
                $_SESSION['db_name'] = $dbName;
                $_SESSION['db_user'] = $dbUser;
                $_SESSION['db_pass'] = $dbPass;

                header("Location: index.php?step=3");
                exit;
            } catch (PDOException $e) {
                $error = 'Database Connection Failed: ' . $e->getMessage();
            }
        }
    } elseif ($step === 3) {
        $adminMobile = trim($_POST['admin_mobile'] ?? '');
        $adminPassword = trim($_POST['admin_password'] ?? '');
        $adminName = trim($_POST['admin_name'] ?? 'System Admin');

        if (empty($adminMobile) || empty($adminPassword)) {
            $error = 'Admin Mobile and Password are required.';
        } else {
            try {
                $dbHost = $_SESSION['db_host'] ?? 'localhost';
                $dbPort = $_SESSION['db_port'] ?? '3306';
                $dbName = $_SESSION['db_name'] ?? '';
                $dbUser = $_SESSION['db_user'] ?? '';
                $dbPass = $_SESSION['db_pass'] ?? '';

                $dsn = "mysql:host={$dbHost};port={$dbPort};dbname={$dbName};charset=utf8mb4";
                $pdo = new PDO($dsn, $dbUser, $dbPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);

                // 1. Run Schema SQL
                $schemaSql = file_get_contents(__DIR__ . '/../database/schema.sql');
                $pdo->exec($schemaSql);

                // 2. Run Seed SQL
                $seedSql = file_get_contents(__DIR__ . '/../database/seed.sql');
                $pdo->exec($seedSql);

                // 3. Create Custom Admin
                $adminHash = password_hash($adminPassword, PASSWORD_BCRYPT);
                $stmt = $pdo->prepare("
                    INSERT INTO users (user_code, mobile, name, password_hash, role, balance, referral_code, status)
                    VALUES ('RP999999', ?, ?, ?, 'admin', 100000.00, 'RPADMIN', 'active')
                    ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash), role = 'admin', name = VALUES(name)
                ");
                $stmt->execute([$adminMobile, $adminName, $adminHash]);

                // 4. Write config/database.php
                $configContent = "<?php\n"
                    . "/**\n * Reliance Pay - Production Database Configuration\n * Auto-generated by Installer on " . date('Y-m-d H:i:s') . "\n */\n\n"
                    . "define('DB_HOST', '" . addslashes($dbHost) . "');\n"
                    . "define('DB_PORT', '" . addslashes($dbPort) . "');\n"
                    . "define('DB_NAME', '" . addslashes($dbName) . "');\n"
                    . "define('DB_USER', '" . addslashes($dbUser) . "');\n"
                    . "define('DB_PASS', '" . addslashes($dbPass) . "');\n\n"
                    . "function getDbConnection(): PDO {\n"
                    . "    static \$pdo = null;\n"
                    . "    if (\$pdo === null) {\n"
                    . "        \$dsn = 'mysql:host=' . DB_HOST . ';port=' . DB_PORT . ';dbname=' . DB_NAME . ';charset=utf8mb4';\n"
                    . "        \$options = [\n"
                    . "            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,\n"
                    . "            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,\n"
                    . "            PDO::ATTR_EMULATE_PREPARES => false,\n"
                    . "        ];\n"
                    . "        \$pdo = new PDO(\$dsn, DB_USER, DB_PASS, \$options);\n"
                    . "    }\n"
                    . "    return \$pdo;\n"
                    . "}\n";

                file_put_contents(__DIR__ . '/../config/database.php', $configContent);

                // 5. Create Lock File
                file_put_contents($lockFile, "Installed on " . date('Y-m-d H:i:s'));

                header("Location: index.php?step=4");
                exit;
            } catch (Exception $e) {
                $error = 'Installation Execution Failed: ' . $e->getMessage();
            }
        }
    }
}
